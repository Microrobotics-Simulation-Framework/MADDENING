def _ensure_stable_only_or_opt_in(
    surface_name: str,
    include_evolving: bool,
) -> bool:
    """Return True iff the named surface is allowed into the FMU.

    The rule (per the v0.3.0 plan §A1): a variable enters the FMU
    surface iff its source/sink is tagged ``@stability(STABLE)`` and
    the caller explicitly opts it in via the FMU export config — *not*
    by default, to keep the public FMU surface minimal.

    The caller's opt-in is selecting which nodes / fields to export.
    The audit-level check is "are the source/sink classes stable?" —
    that's what this function answers.
    """
    level = _STABILITY_REGISTRY.get(surface_name)
    if level == StabilityLevel.STABLE:
        return True
    if include_evolving and level in (
        StabilityLevel.EVOLVING, StabilityLevel.PROVISIONAL,
    ):
        return True
    return False


def _xs_float(x: float) -> str:
    """``x`` as an XML Schema ``float`` / ``double`` literal.

    ``repr(float("inf"))`` is ``'inf'``, which is not an ``xs:float``
    lexical value, so an FMU carrying a non-finite parameter start used
    to fail schema validation.  The three special values have their own
    spellings (``INF``, ``-INF``, ``NaN``); everything else is ``repr``
    as before, which round-trips a double exactly.
    """
    if math.isnan(x):
        return "NaN"
    if math.isinf(x):
        return "INF" if x > 0 else "-INF"
    return repr(x)


def _advertised_bound(spec, side: int, dtype: str) -> Optional[float]:
    """``ParamSpec.bounds[side]`` as the FMI ``min`` / ``max`` attribute.

    FMI's ``min`` / ``max`` are inclusive, but a ``log`` / ``logit``
    leaf's bound is *open* (``p > lo`` strictly -- ``ParamSpec.check``
    and therefore the sidecar refuse ``p == lo``).  Advertise the
    nearest representable value inside the interval instead, so every
    value the XML declares settable is accepted by ``set_params``.  A
    zero bound's neighbour is a float32 subnormal, which XLA:CPU flushes
    to zero (``jnp.asarray(1e-45) <= 0.0`` is ``True``), so the margin
    is never smaller than the smallest normal.
    """
    if spec is None:
        return None
    b = spec.bounds[side]
    if b is None:
        return None
    if spec.transform not in ("log", "logit"):
        return b
    try:
        dt = np.dtype(dtype)
        if not np.issubdtype(dt, np.floating):
            dt = np.dtype(np.float32)
    except TypeError:
        dt = np.dtype(np.float32)
    fi = np.finfo(dt)
    towards = dt.type(np.inf) if side == 0 else dt.type(-np.inf)
    m = np.nextafter(dt.type(b), towards)
    if abs(m) < fi.tiny:
        m = dt.type(fi.tiny if side == 0 else -fi.tiny)
    return float(m)


@dataclass(frozen=True)
class _ExtView:
    """Duck-typed view of an external input for the builder."""
    target_node: str
    target_field: str
    shape: tuple
    dtype: Any
    description: str = ""
    expected_units: str = ""


def _master_timestep(graph_manager: Any) -> float:
    """The graph's base (fastest) timestep: ``_base_dt`` when compile()
    set it, else the smallest node timestep; 1e-3 for an empty graph."""
    base = getattr(graph_manager, "_base_dt", None)
    if base:
        return float(base)
    nodes = getattr(graph_manager, "_nodes", {}) or {}
    dts = [
        float(getattr(spec, "timestep", getattr(getattr(spec, "node", spec), "delta_t", 0.0)))
        for spec in nodes.values()
    ]
    dts = [dt for dt in dts if dt > 0]
    return min(dts) if dts else 1.0e-3


def _deterministic_token(parts: Iterable[str]) -> str:
    """Build a stable, GUID-shaped token from a list of strings.

    We don't use Python's ``uuid`` because the token must be a pure
    function of the graph's structural fingerprint (any FMU loader
    refuses to instantiate when the token doesn't match the runtime
    DLL's compile-time token).  See FMI 3.0 §2.2.3.
    """
    import hashlib  # noqa: PLC0415 — stdlib lazy import
    h = hashlib.sha256()
    for part in parts:
        h.update(part.encode("utf-8"))
        h.update(b"\0")
    digest = h.hexdigest()
    # Format as 8-4-4-4-12 GUID for tooling that pattern-matches it.
    return f"{digest[:8]}-{digest[8:12]}-{digest[12:16]}-{digest[16:20]}-{digest[20:32]}"


def _owner(var: "FMIVariable") -> str:
    """``"the <causality> of node 'n', field 'f'"`` for a clash message."""
    if var.node is None:
        return f"the {var.causality} {var.name!r}"
    return f"the {var.causality} of node {var.node!r}, field {var.field!r}"


@stability(StabilityLevel.EVOLVING)
def build_model_description(
    graph_manager: Any,
    *,
    model_name: str,
    selected_inputs: Optional[Iterable[str]] = None,
    selected_outputs: Optional[Iterable[tuple[str, str]]] = None,
    include_evolving: bool = False,
    default_step_size: Optional[float] = None,
    include_parameters: bool = True,
    multi_clock: bool = False,
    model_identifier: Optional[str] = None,
) -> ModelDescription:
    """Build an FMI 3.0 :class:`ModelDescription` from a ``GraphManager``.

    Parameters
    ----------
    graph_manager : GraphManager
        A *compiled* graph.  The structure (nodes, edges, external
        inputs) is read at build time.
    model_name : str
        Identifier the FMU will be called by.  Becomes ``modelName``
        in the XML.
    selected_inputs : iterable of str, optional
        FMU input variables to surface.  Names must match the graph's
        registered external-input keys.  When ``None`` (default),
        every external input is included.
    selected_outputs : iterable of (node, field) tuples, optional
        Which per-node state fields to expose as FMU outputs.  When
        ``None`` (default), every state field of every node is
        included.
    include_evolving : bool, default False
        If ``True``, also include surfaces tagged
        ``@stability(EVOLVING)`` or ``PROVISIONAL``.  Default keeps
        the FMU's public surface minimal — only ``STABLE``-tagged
        sources/sinks contribute.
    default_step_size : float, optional
        Default fixed step size for the FMU's experiment block.
        Defaults to the graph's master timestep when available.
    include_parameters : bool, default True
        Expose every leaf of ``graph_manager.params["nodes"]`` as a
        ``causality="parameter"``, ``variability="tunable"`` variable
        named ``<node>.params.<key>`` (same stability filter as outputs), with
        ``description`` / ``unit`` from the node's
        :class:`~maddening.core.params.ParamSpec`.  These are backed by
        the graph parameter pytree, so an importer that sets one changes
        the next step without a recompile, and the FMU's directional
        derivatives with respect to them are the real ``jax.jvp``.
    multi_clock : bool, default False
        Emit one FMI 3.0 ``<Clock>`` (``intervalVariability="constant"``)
        per distinct node timestep among the exported nodes, and tag every
        exported output and external input with the clock of its node
        (``clocks=`` attribute, ``variability="discrete"``): an importer
        then knows that a node on a 10x coarser rate only changes every
        10th master step.  Clocks are named ``clock_<k>`` in order of
        increasing interval; the fastest one equals the default step
        size.  Off by default (single-clock, every output continuous),
        so existing FMUs are unchanged.
    model_identifier : str, optional
        Emit a ``<CoSimulation modelIdentifier=...>`` element naming the
        FMU binary (``maddening.fmi.package`` uses ``"maddening_fmu"``).
        ``None`` (default) emits a description-only document.

    Returns
    -------
    ModelDescription
    """
    # Inputs: read external-input edges from the graph manager.  The
    # graph manager exposes them via ``_external_input_specs`` (an
    # internal dict) — we accept a duck-typed view for tests.
    ext_specs = getattr(graph_manager, "_external_input_specs", None)
    if ext_specs is None:
        # A real GraphManager keeps ``_external_inputs`` (a list of
        # ExternalInputSpec); key them ``<node>.<field>`` -- unique, and
        # the same convention as outputs -- and borrow description /
        # units from the target node's boundary_input_spec().
        ext_specs = {}
        for ei in getattr(graph_manager, "_external_inputs", None) or []:
            target = getattr(ei, "target_node", None)
            fld = getattr(ei, "target_field", None)
            if target is None or fld is None:
                continue
            node_spec = (getattr(graph_manager, "_nodes", {}) or {}).get(target)
            node = getattr(node_spec, "node", node_spec)
            bis = {}
            try:
                bis = node.boundary_input_spec() if node is not None else {}
            except Exception:  # noqa: BLE001 - descriptor is advisory
                bis = {}
            declared = bis.get(fld)
            raw_dtype = getattr(ei, "dtype", "float32")
            try:
                dtype_name = np.dtype(raw_dtype).name       # jnp.float32 -> "float32"
            except TypeError:
                dtype_name = str(raw_dtype)
            ext_specs[f"{target}.{fld}"] = _ExtView(
                target_node=target, target_field=fld,
                shape=tuple(getattr(ei, "shape", ()) or ()),
                dtype=dtype_name,
                description=getattr(declared, "description", "") or "",
                expected_units=getattr(declared, "expected_units", "") or "",
            )
    selected_input_keys = (
        set(selected_inputs) if selected_inputs is not None
        else set(ext_specs.keys())
    )

    variables: list[FMIVariable] = []
    next_vr = 1  # FMI uses 1-based valueReference

    # ----- Independent variable (FMI 3.0 §2.2.7 mandates exactly one) -----
    # Time is the universal independent variable for fixed-step / continuous
    # simulation.  FMU loaders (e.g. FMPy) refuse a modelDescription.xml
    # missing it.
    variables.append(FMIVariable(
        name="time",
        value_reference=next_vr,
        dtype="float64",
        causality="independent",
        variability="continuous",
        description="Simulation time (independent variable).",
        unit="s",
    ))
    next_vr += 1

    # ----- Clocks (multi-rate export) -----
    nodes = getattr(graph_manager, "_nodes", {})
    clock_vr_of_dt: dict[float, int] = {}
    node_clock: dict[str, int] = {}
    if multi_clock:
        dts: dict[float, list[str]] = {}
        for node_name, node_spec in nodes.items():
            node = getattr(node_spec, "node", node_spec)
            cls_name = f"{type(node).__module__}.{type(node).__name__}"
            if not _ensure_stable_only_or_opt_in(cls_name, include_evolving):
                continue
            dt = float(getattr(node_spec, "timestep", getattr(node, "delta_t", 0.0)))
            dts.setdefault(dt, []).append(node_name)
        for k, dt in enumerate(sorted(dts)):
            variables.append(FMIVariable(
                name=f"clock_{k}",
                value_reference=next_vr,
                dtype=_CLOCK_DTYPE,
                causality="input",
                variability="discrete",
                description=(
                    f"Rate {dt!r} s: ticks when nodes "
                    f"{', '.join(sorted(dts[dt]))} update."
                ),
                interval_decimal=dt,
            ))
            clock_vr_of_dt[dt] = next_vr
            for n in dts[dt]:
                node_clock[n] = next_vr
            next_vr += 1

    def _clocked(node_name: str) -> tuple[tuple[int, ...], str]:
        """``(clocks, variability)`` for a variable owned by ``node_name``."""
        vr = node_clock.get(node_name)
        return ((vr,), "discrete") if vr is not None else ((), "continuous")

    # ----- Inputs -----
    for ext_key, ext_spec in ext_specs.items():
        if ext_key not in selected_input_keys:
            continue
        dtype = getattr(ext_spec, "dtype", "float32")
        if not isinstance(dtype, str):
            dtype = getattr(dtype, "name", str(dtype))
        shape = tuple(getattr(ext_spec, "shape", ()) or ())
        unit = getattr(ext_spec, "expected_units", "") or ""
        clocks, variability = _clocked(str(getattr(ext_spec, "target_node", "")))
        # FMI 3.0 requires a start value on every input; the graph's own
        # default for an unset external input is zero, so advertise that.
        n_elems = int(np.prod(shape)) if shape else 1
        variables.append(FMIVariable(
            name=ext_key,
            value_reference=next_vr,
            dtype=dtype,
            causality="input",
            variability=variability,
            description=getattr(ext_spec, "description", "") or "",
            unit=unit,
            node=str(getattr(ext_spec, "target_node", "") or ""),
            field=str(getattr(ext_spec, "target_field", "") or ""),
            shape=shape or None,
            clocks=clocks,
            start=" ".join(["0.0"] * n_elems),
        ))
        next_vr += 1

    # ----- Outputs -----
    selected_output_set = (
        set((n, f) for (n, f) in (selected_outputs or []))
    )
    for node_name, node_spec in nodes.items():
        node = getattr(node_spec, "node", node_spec)
        node_class_name = (
            f"{type(node).__module__}.{type(node).__name__}"
        )
        if not _ensure_stable_only_or_opt_in(node_class_name, include_evolving):
            # Node's class isn't part of the public FMU surface yet.
            continue
        for field_name in node.state_fields():
            if selected_outputs is not None and \
                    (node_name, field_name) not in selected_output_set:
                continue
            initial = node.initial_state()[field_name]
            dtype = str(getattr(initial, "dtype", "float32"))
            shape = tuple(getattr(initial, "shape", ()) or ())
            clocks, variability = _clocked(node_name)
            variables.append(FMIVariable(
                name=f"{node_name}.{field_name}",
                value_reference=next_vr,
                dtype=dtype,
                causality="output",
                variability=variability,
                description=f"State field {field_name!r} of node "
                            f"{node_name!r}",
                node=node_name,
                field=field_name,
                shape=shape or None,
                clocks=clocks,
            ))
            next_vr += 1

    # ----- Parameters (graph parameter pytree) -----
    if include_parameters:
        used = {v.name for v in variables}
        node_params = getattr(graph_manager, "params", {}) or {}
        node_params = node_params.get("nodes", {}) if isinstance(node_params, dict) else {}
        specs_fn = getattr(graph_manager, "param_specs", None)
        all_specs = specs_fn().get("nodes", {}) if callable(specs_fn) else {}
        for node_name, leaves in node_params.items():
            node_spec = nodes.get(node_name)
            node = getattr(node_spec, "node", node_spec)
            node_class_name = f"{type(node).__module__}.{type(node).__name__}"
            if not _ensure_stable_only_or_opt_in(node_class_name, include_evolving):
                continue
            node_specs = all_specs.get(node_name, {})
            for key, leaf in leaves.items():
                # Own namespace, mirroring params["nodes"][node][key]: a
                # parameter may share its key with a state field (a
                # node's initial position, say) and must not clash with
                # the "<node>.<field>" output.
                name = f"{node_name}.params.{key}"
                if name in used:  # pragma: no cover - defensive
                    raise ValueError(f"FMU variable name clash: {name!r}")
                used.add(name)
                spec = node_specs.get(key)
                dtype = str(getattr(leaf, "dtype", "float32"))
                shape = tuple(getattr(leaf, "shape", ()) or ())
                flat = np.asarray(leaf).ravel()
                start = " ".join(_xs_float(float(x)) for x in flat)
                variables.append(FMIVariable(
                    name=name,
                    value_reference=next_vr,
                    dtype=dtype,
                    causality="parameter",
                    variability="tunable",
                    description=(
                        (spec.description if spec is not None and spec.description else "")
                        or f"Parameter {key!r} of node {node_name!r}"
                    ),
                    unit=(spec.units if spec is not None else "") or "",
                    shape=shape or None,
                    start=start,
                    min=_advertised_bound(spec, 0, dtype),
                    max=_advertised_bound(spec, 1, dtype),
                ))
                next_vr += 1

    # ----- Name uniqueness -----
    # FMI requires every variable name to be unique.  A graph node name
    # may contain a '.', which FMI reads as a name-space separator, so two
    # different (node, field) pairs can spell the same FMU name -- the one
    # ambiguity carrying ``node``/``field`` on the variable cannot resolve.
    # Refuse the export naming both owners instead of writing an FMU whose
    # variables an importer cannot tell apart.
    seen: dict[str, FMIVariable] = {}
    for var in variables:
        clash = seen.get(var.name)
        if clash is not None:
            raise ValueError(
                f"FMU variable name clash: {var.name!r} would name both "
                f"{_owner(clash)} and {_owner(var)}.  FMI variable names must "
                "be unique and a '.' in a node name is not distinguishable "
                "from the separator; rename one of them."
            )
        seen[var.name] = var

    # ----- Defaults -----
    if default_step_size is None:
        default_step_size = _master_timestep(graph_manager)

    # Deterministic instantiationToken — depends on the schema, so
    # the FMU loader refuses mismatched schemas at instantiation.
    token = _deterministic_token([
        model_name,
        *[f"{v.name}:{v.dtype}:{v.causality}:{v.shape!r}" for v in variables],
        f"step:{default_step_size}",
    ])

    return ModelDescription(
        model_name=model_name,
        instantiation_token=token,
        variables=variables,
        default_step_size=default_step_size,
        co_simulation_model_identifier=model_identifier,
    )


