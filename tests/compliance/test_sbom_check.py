def test_a_soup_document_without_a_base_dependencies_row_fails_closed(tmp_path):
    pyproject = _pyproject_with_extras()
    _write_dir(tmp_path, pyproject)
    text = _soup_text().replace("Base Dependencies", "Dependencies")
    errors, _ = check_sbom.check_directory(tmp_path, pyproject=pyproject, soup_text=text)
    assert _has(errors, "no 'Base Dependencies' row")
    with pytest.raises(ValueError, match="empty"):
        check_sbom.soup_items(_soup_text(row=""))
    with pytest.raises(ValueError, match="no generated"):
        check_sbom.soup_items("no table here")


def test_a_specifier_with_a_spaced_comma_stays_one_soup_item():
    text = _soup_text(row="jax>=0.10, <0.13, numpy>=1.24")
    assert check_sbom.soup_items(text) == ["jax>=0.10,<0.13", "numpy>=1.24"]


def test_the_cli_names_a_planted_defect_and_exits_non_zero(tmp_path):
    pyproject = _pyproject_with_extras()
    sbom_dir = tmp_path / "sbom"
    _write_dir(sbom_dir, pyproject)
    path = sbom_dir / check_sbom.sbom_filename(VERSION, "server")
    planted = mutate(json.loads(path.read_text()),
                     lambda s: s["components"].remove(component(s, "pyzmq")))
    path.write_text(check_sbom.dumps(planted))
    toml = tmp_path / "pyproject.toml"
    extras = pyproject["project"]["optional-dependencies"]
    toml.write_text(
        "[project]\nname = \"maddening\"\n"
        f"version = \"{VERSION}\"\nlicense = \"LGPL-3.0-or-later\"\n"
        f"dependencies = {json.dumps(pyproject['project']['dependencies'])}\n"
        "[project.optional-dependencies]\n"
        + "".join(f"{k} = {json.dumps(v)}\n" for k, v in extras.items()))
    soup = tmp_path / "soup.md"
    soup.write_text(_soup_text())
    result = subprocess.run(
        [sys.executable, str(SCRIPTS / "check_sbom.py"), "--sbom-dir", str(sbom_dir),
         "--pyproject", str(toml), "--soup", str(soup)],
        capture_output=True, text=True)
    assert result.returncode == 1
    assert "server.cdx.json: direct dependency pyzmq>=25.0" in result.stderr
    assert "names no component" in result.stderr        # the edges left behind
    assert "FAILED: " in result.stderr


