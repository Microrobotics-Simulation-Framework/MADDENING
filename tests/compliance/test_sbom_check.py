"""The committed SBOMs must describe the package ``pyproject.toml`` declares.

``docs/validation/sbom/`` holds one CycloneDX SBOM per covered install,
generated by ``scripts/generate_sbom.py`` from a clean install of the
wheel (network access, uv).  ``scripts/check_sbom.py`` compares them with
``pyproject.toml`` and the SOUP package offline, and this module runs it on
the committed files, so a dependency change or a version bump that is not
followed by a regeneration fails in CI's ``pytest tests/compliance/`` step.

Most of the module is the other direction: each defect the check exists
to catch is planted in a small fixture SBOM, and the check has to name it.
The fixtures are re-sealed after each mutation (their serial recomputed),
so it is the targeted rule that fires and not only the hand-edit guard;
that guard has tests of its own.  The generator's pure half
(``finalise``, ``installed_mismatch``) is tested the same way, with no
network.
"""

from __future__ import annotations

