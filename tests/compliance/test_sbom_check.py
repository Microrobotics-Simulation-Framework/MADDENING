@pytest.mark.parametrize("change, fragment", [
    (lambda c: c.pop("purl"), "has no purl"),
    (lambda c: c.update(purl="pkg:pypi/numpie@2.5.3"), "names a different package"),
    (lambda c: c.update(purl="pkg:pypi/numpy@2.5.2"), "names version '2.5.2'"),
    (lambda c: c.update(purl="pkg:npm/numpy@2.5.3"), "is not a pkg:pypi purl"),
    (lambda c: c.pop("version"), "has no version"),
])
def test_a_bad_component_purl_or_version_is_named(change, fragment):
    sbom = mutate(make_sbom(), lambda s: change(component(s, "numpy")))
    assert _has(errors_of(sbom), "component numpy", fragment)


