def _soup_text(installs=check_sbom.SBOM_INSTALLS, version=VERSION,
               row="jax>=0.10,<0.13, numpy>=1.24, pyyaml>=6.0") -> str:
    names = "\n".join(f"- `{check_sbom.sbom_filename(version, i)}`" for i in installs)
    return (
        "## 1. Software Identification\n\n"
        "<!-- BEGIN GENERATED: software-identification -- x -->\n"
        "| Field | Value |\n|---|---|\n"
        f"| Base Dependencies | {row} |\n"
        "<!-- END GENERATED: software-identification -->\n\n"
        f"## 6. SBOM\n\n{names}\n"
    )


def _pyproject_with_extras() -> dict:
    out = copy.deepcopy(PYPROJECT)
    extras = out["project"]["optional-dependencies"]
    extras.update({"server": ["pyzmq>=25.0"], "surrogates": ["optax>=0.1"],
                   "usd": ["usd-core>=21.8"]})
    return out


_EXTRA_COMPONENTS = {"core": {}, "server": {"pyzmq": "27.2.0"},
                     "surrogates": {"optax": "0.2.8"}, "usd": {"usd-core": "26.8"}}


def _write_dir(path: Path, pyproject: dict, installs=check_sbom.SBOM_INSTALLS,
               version=VERSION) -> None:
    path.mkdir(parents=True, exist_ok=True)
    for install in installs:
        sbom = make_sbom(install, {**CORE, **_EXTRA_COMPONENTS[install]},
                         version=version, pyproject=pyproject)
        (path / check_sbom.sbom_filename(version, install)).write_text(
            check_sbom.dumps(sbom), encoding="utf-8")


def test_a_consistent_directory_passes(tmp_path):
    pyproject = _pyproject_with_extras()
    _write_dir(tmp_path, pyproject)
    errors, sboms = check_sbom.check_directory(tmp_path, pyproject=pyproject,
                                               soup_text=_soup_text())
    assert errors == [] and len(sboms) == 4


def test_a_missing_sbom_for_a_covered_install_is_named(tmp_path):
    pyproject = _pyproject_with_extras()
    _write_dir(tmp_path, pyproject, installs=("core", "server", "usd"))
    errors, _ = check_sbom.check_directory(tmp_path, pyproject=pyproject,
                                           soup_text=_soup_text())
    assert _has(errors, f"maddening-{VERSION}-surrogates.cdx.json: missing",
                "generate_sbom.py")


def test_a_version_bump_without_regenerating_fails(tmp_path):
    """The release step the check enforces: new version, old files."""
    pyproject = _pyproject_with_extras()
    _write_dir(tmp_path, pyproject)
    bumped = copy.deepcopy(pyproject)
    bumped["project"]["version"] = "10.0.0"
    errors, _ = check_sbom.check_directory(tmp_path, pyproject=bumped,
                                           soup_text=_soup_text(version="10.0.0"))
    assert _has(errors, "maddening-10.0.0-core.cdx.json: missing")
    assert _has(errors, f"maddening-{VERSION}-core.cdx.json: unexpected SBOM",
                "a previous version's file")


def test_an_sbom_for_an_uncovered_install_is_named(tmp_path):
    pyproject = _pyproject_with_extras()
    _write_dir(tmp_path, pyproject)
