def test_a_soup_item_is_held_to_the_pyproject_range_not_the_documents():
    """The SOUP row may say anything; pyproject's range is the one checked."""
    sbom = make_sbom(components={**CORE, "jax": "0.13.0"})
    errors = errors_of(sbom, soup=["jax>=0.1"] + SOUP_ITEMS[1:])
    assert _has(errors, "SOUP item jax is at 0.13.0", "jax<0.13,>=0.10")


