def test_finalise_is_independent_of_the_order_cyclonedx_wrote():
    raw = _raw(CORE, [])
    flipped = copy.deepcopy(raw)
    flipped["components"].reverse()
    flipped["dependencies"].reverse()
    a, b = _finalise(raw, _probe(CORE)), _finalise(flipped, _probe(CORE))
    assert check_sbom.dumps(a) == check_sbom.dumps(b)


def test_installed_mismatch_catches_a_leaked_and_a_dropped_package():
    sbom = _finalise(_raw(CORE, []), _probe(CORE))
    assert generate_sbom.installed_mismatch(sbom, _probe(CORE)["distributions"]) == []
    leaked = _probe(CORE)["distributions"] + [["pip", "25.0"]]
    assert generate_sbom.installed_mismatch(sbom, leaked) == [
        "pip: installed 25.0, in the SBOM None"]
    dropped = [d for d in _probe(CORE)["distributions"] if d[0] != "numpy"]
    assert generate_sbom.installed_mismatch(sbom, dropped) == [
        "numpy: installed None, in the SBOM 2.5.3"]


def test_the_timestamp_is_the_cutoff_unless_source_date_epoch_is_set(monkeypatch):
    cutoff = generate_sbom._parse_cutoff("2026-09-25")
    monkeypatch.delenv("SOURCE_DATE_EPOCH", raising=False)
    assert generate_sbom._timestamp(cutoff) == "2026-09-25T00:00:00Z"
    monkeypatch.setenv("SOURCE_DATE_EPOCH", "0")
    assert generate_sbom._timestamp(cutoff) == "1970-01-01T00:00:00Z"
    assert generate_sbom._parse_cutoff("2026-09-25T12:30:00+02:00").hour == 10
