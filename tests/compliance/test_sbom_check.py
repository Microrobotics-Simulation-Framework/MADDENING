def test_the_committed_sboms_match_pyproject_and_the_soup_package():
    """The gate itself, on the repository: a stale SBOM fails here."""
    errors, sboms = check_sbom.check_directory(
        check_sbom.SBOM_DIR, pyproject=check_sbom.load_pyproject(),
        soup_text=check_sbom.SOUP_PACKAGE.read_text(encoding="utf-8"))
    assert not errors, (
        "the committed SBOMs disagree with their sources; regenerate them with "
        "`python scripts/generate_sbom.py` (network, uv) and commit the result:\n"
        + "\n".join(errors))
    assert len(sboms) == len(check_sbom.SBOM_INSTALLS)


def test_the_check_script_passes_on_the_repository_as_ci_runs_it():
    result = subprocess.run([sys.executable, str(SCRIPTS / "check_sbom.py")],
                            capture_output=True, text=True, cwd=REPO_ROOT)
    assert result.returncode == 0, result.stderr
    assert result.stdout.startswith(f"OK: {len(check_sbom.SBOM_INSTALLS)} SBOMs")


def test_the_soup_items_read_are_exactly_the_base_dependencies():
    """The parser must find every item, or the SOUP rule checks a subset."""
    text = check_sbom.SOUP_PACKAGE.read_text(encoding="utf-8")
    assert check_sbom.soup_items(text) == check_sbom.load_pyproject()["project"]["dependencies"]


def test_every_committed_sbom_is_one_generation_of_its_content():
    """Sealed, in canonical order, and written in the on-disk form."""
    for path in sorted(check_sbom.SBOM_DIR.glob("*.cdx.json")):
        text = path.read_text(encoding="utf-8")
        sbom = json.loads(text)
        assert check_sbom.dumps(check_sbom.seal(sbom)) == text, path.name


