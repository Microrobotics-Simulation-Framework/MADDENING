def test_sealing_is_deterministic_and_idempotent():
    a = make_sbom()
    assert check_sbom.seal(a) == a
    shuffled = copy.deepcopy(a)
    shuffled["components"].reverse()
    shuffled["dependencies"].reverse()
    shuffled["metadata"]["properties"].reverse()
    assert check_sbom.dumps(check_sbom.seal(shuffled)) == check_sbom.dumps(a)


def test_the_serial_changes_with_the_content():
    a = make_sbom()
    b = mutate(a, lambda s: component(s, "numpy").update(version="2.5.4"))
    assert a["serialNumber"] != b["serialNumber"]
    assert a["serialNumber"].startswith("urn:uuid:")


def test_normalising_drops_exactly_the_date_dependent_fields():
    a = make_sbom()
    b = mutate(a, lambda s: (
        s["metadata"].update(timestamp="2027-01-01T00:00:00Z"),
        next(p for p in s["metadata"]["properties"]
             if p["name"] == check_sbom.PROP_EXCLUDE_NEWER).update(value="2027-01-01"),
    ))
    assert a != b
    na, nb = check_sbom.normalise(a), check_sbom.normalise(b)
    assert na == nb
    assert "serialNumber" not in na and "timestamp" not in na["metadata"]
    kept = {p["name"] for p in na["metadata"]["properties"]}
    assert check_sbom.PROP_INSTALL in kept and check_sbom.PROP_EXCLUDE_NEWER not in kept
    # A resolved-environment difference survives normalisation.
    c = mutate(a, lambda s: component(s, "numpy").update(version="2.5.4"))
    assert check_sbom.normalise(c) != na


